#!/usr/bin/env python3
"""gen_credit_seed.py — writes db/seed/104_credit_scorecard.sql, and the tables of docs/35, from
tools/dbgen/credit_scorecard.json (the credit assessment methodology, docs/35 and ADR 0017).

Usage: python3 tools/dbgen/gen_credit_seed.py [out.sql] [--doc | --doc-check]
  out.sql  where to write the seed (default db/seed/104_credit_scorecard.sql); CI writes it to a temporary file and
           compares, so the committed seed cannot drift from the methodology file
  --doc    also rewrites the generated tables of docs/35-credit-assessment-methodology.md between their markers
           <!-- gen:NAME --> and <!-- /gen:NAME -->
  --doc-check  changes nothing in docs/35 and exits 1 if its generated tables differ from the methodology file (CI)
The seed inserts only: a scorecard is written as DRAFT with its metrics, item rules and adjustments, then approved;
an approved scorecard is never changed (046 refuses it), so a change to the methodology is a new version.
"""
import json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..', '..')
M = json.load(open(os.path.join(HERE, 'credit_scorecard.json'), encoding='utf-8'))
args = [a for a in sys.argv[1:] if not a.startswith('--')]
OUT = args[0] if args else os.path.join(ROOT, 'db', 'seed', '104_credit_scorecard.sql')
DOC = os.path.join(ROOT, 'docs', '35-credit-assessment-methodology.md')
EFFECTIVE = '2026-10-18'
METRIC = {m['code']: m for m in M['metrics']}


def q(s):
    return 'NULL' if s is None else "N'" + str(s).replace("'", "''") + "'"


def a(s):
    return 'NULL' if s is None else "'" + str(s) + "'"


def n(x):
    if x is None:
        return 'NULL'
    if isinstance(x, bool):
        return '1' if x else '0'
    return repr(x) if isinstance(x, int) else ('%.6f' % x).rstrip('0').rstrip('.')


def vals(rows):
    """VALUES rows, indented under a derived table, separated by commas."""
    return ',\n'.join('    ' + r for r in rows)


def check():
    """The methodology is consistent before anything is written."""
    for c in M['scorecards']:
        w = sum(sm['w'] for sm in c['metrics'])
        assert abs(w - 100) < 1e-9, f"{c['code']}: weights add up to {w}"
        for sm in c['metrics']:
            md = METRIC[sm['m']]
            if md['kind'] == 'QUALITATIVE':
                assert 'b' not in sm, f"{c['code']} {sm['m']}: a qualitative metric has no grid"
                continue
            b = sm['b']
            assert len(b) == 9, f"{c['code']} {sm['m']}: nine boundaries"
            asc = all(b[i] < b[i + 1] for i in range(8))
            desc = all(b[i] > b[i + 1] for i in range(8))
            assert (asc and md['dir'] == 'LOWER_BETTER') or (desc and md['dir'] == 'HIGHER_BETTER'), \
                f"{c['code']} {sm['m']}: the grid does not run from best to worst in the metric's direction"
        for ir in c['items']:
            md, t = METRIC[ir['r']], ir['t']
            asc = all(t[i] < t[i + 1] for i in range(3))
            desc = all(t[i] > t[i + 1] for i in range(3))
            assert (asc and md['dir'] == 'LOWER_BETTER') or (desc and md['dir'] == 'HIGHER_BETTER'), \
                f"{c['code']} item {ir['r']}: thresholds out of order"
    for g in M['grades']:
        assert g['category'] in M['category_text']


def seed():
    L = []
    L.append(f"""/* ============================================================================
   BankFas - 104: the credit assessment methodology of the platform (docs/35-credit-assessment-methodology.md,
   ADR 0017; owner request of 2026-10-18). GENERATED by tools/dbgen/gen_credit_seed.py from
   tools/dbgen/credit_scorecard.json: do not edit by hand.
     fin.RatingGrade          the {len(M['grades'])} grades of the Moody's long-term scale and their range on the continuum
     fin.CreditMetric         the {len(M['metrics'])} metrics: definitions, units, directions and texts
     fin.Scorecard            {len(M['scorecards'])} sector scorecards, version 1, approved on {EFFECTIVE}
     fin.ScorecardMetric      their weights and grids
     fin.ScorecardItemRule    their balance-sheet item rules
     fin.ScorecardAdjustment  their adjustments
   The thresholds are a calibration by expert judgment on the Moody's global scale, not Moody's own grids; the bank's
   credit risk function validates them before the grades are used in a credit decision (docs/35 section 12).
   Insert only: a scorecard is written as DRAFT with its rows and then approved; an approved scorecard is never
   changed (fin.TR_Scorecard_Lifecycle, 046), so a second run changes nothing and a new calibration is a new version.
   ============================================================================ */
SET NOCOUNT ON;
SET ANSI_NULLS ON; SET QUOTED_IDENTIFIER ON; SET ANSI_PADDING ON; SET ANSI_WARNINGS ON; SET ARITHABORT ON; SET CONCAT_NULL_YIELDS_NULL ON; SET NUMERIC_ROUNDABORT OFF;
GO""")
    rows = []
    for g in M['grades']:
        ar, en = M['category_text'][g['category']]
        rows.append(f"    ({a(g['code'])}, {g['notch']}, {a(g['category'])}, {n(g['from'])}, {n(g['to'])}, {a(g['band'])}, {n(g['ig'])}, {q(ar)}, {q(en)})")
    L.append("MERGE fin.RatingGrade AS d\nUSING (VALUES\n" + ",\n".join(rows) + """
) AS s (Code, NotchNo, Category, ScoreFrom, ScoreTo, RiskBand, IsInvestmentGrade, DescriptionAr, DescriptionEn)
   ON d.Code = s.Code
WHEN NOT MATCHED THEN
    INSERT (Code, NotchNo, Category, ScoreFrom, ScoreTo, RiskBand, IsInvestmentGrade, DescriptionAr, DescriptionEn)
    VALUES (s.Code, s.NotchNo, s.Category, s.ScoreFrom, s.ScoreTo, s.RiskBand, s.IsInvestmentGrade, s.DescriptionAr, s.DescriptionEn);
GO""")
    rows = []
    for m in M['metrics']:
        rows.append(f"    ({a(m['code'])}, {q(m['ar'])}, {q(m['en'])}, {a(m['kind'])}, {a(m['unit'])}, {a(m['dir'])},\n"
                    f"     {q(m['def'])},\n     {q(m['inputs'])}, {q(m['s'][0])}, {q(m['s'][1])}, {q(m['w'][0])}, {q(m['w'][1])})")
    L.append("MERGE fin.CreditMetric AS d\nUSING (VALUES\n" + ",\n".join(rows) + """
) AS s (Code, NameAr, NameEn, Kind, Unit, Direction, DefinitionAr, InputsText, StrengthTextAr, StrengthTextEn, WeaknessTextAr, WeaknessTextEn)
   ON d.Code = s.Code
WHEN NOT MATCHED THEN
    INSERT (Code, NameAr, NameEn, Kind, Unit, Direction, DefinitionAr, InputsText, StrengthTextAr, StrengthTextEn, WeaknessTextAr, WeaknessTextEn)
    VALUES (s.Code, s.NameAr, s.NameEn, s.Kind, s.Unit, s.Direction, s.DefinitionAr, s.InputsText, s.StrengthTextAr, s.StrengthTextEn, s.WeaknessTextAr, s.WeaknessTextEn);
GO""")
    dis_ar, dis_en = M['disclaimer']
    for c in M['scorecards']:
        code, ver = a(c['code']), c['version']
        L.append(f"""-- {c['code']} version {ver}: {c['en']}
IF NOT EXISTS (SELECT 1 FROM fin.Scorecard WHERE Code = {code} AND VersionNo = {ver})
    INSERT fin.Scorecard (Code, VersionNo, NameAr, NameEn, SectorNoteAr, CurrencyId, AmountUnit, MinCoveragePct, QualitativeBoundNotches,
                          SupportMaxAgeMonths, Status, DisclaimerAr, DisclaimerEn)
    SELECT {code}, {ver}, {q(c['ar'])}, {q(c['en'])},
           {q(c['sector'])},
           cu.CurrencyId, {c['amount_unit']}, {n(c['min_coverage'])}, {M['qualitative_bound']}, {M['support_max_age_months']}, 'DRAFT',
           {q(dis_ar)},
           {q(dis_en)}
    FROM ref.Currency AS cu WHERE cu.Code = {a(c['currency'])};""")
        rows = []
        for i, sm in enumerate(c['metrics'], 1):
            b = sm.get('b') or [None] * 9
            rows.append(f"    ({a(sm['m'])}, {a(sm['f'])}, {n(sm['w'])}, " + ", ".join(n(x) for x in b) + f", {i})")
        L.append(f"""MERGE fin.ScorecardMetric AS d
USING (SELECT sc.ScorecardId, m.CreditMetricId, v.FactorCode, v.Weight, v.B0, v.B1, v.B2, v.B3, v.B4, v.B5, v.B6, v.B7, v.B8, v.SortOrder
       FROM (VALUES
{vals(rows)}
            ) AS v (MetricCode, FactorCode, Weight, B0, B1, B2, B3, B4, B5, B6, B7, B8, SortOrder)
       JOIN fin.Scorecard AS sc ON sc.Code = {code} AND sc.VersionNo = {ver} AND sc.Status = 'DRAFT'
       JOIN fin.CreditMetric AS m ON m.Code = v.MetricCode) AS s
   ON d.ScorecardId = s.ScorecardId AND d.MetricId = s.CreditMetricId
WHEN NOT MATCHED THEN
    INSERT (ScorecardId, MetricId, FactorCode, Weight, B0, B1, B2, B3, B4, B5, B6, B7, B8, SortOrder)
    VALUES (s.ScorecardId, s.CreditMetricId, s.FactorCode, s.Weight, s.B0, s.B1, s.B2, s.B3, s.B4, s.B5, s.B6, s.B7, s.B8, s.SortOrder);""")
        rows = []
        for i, ir in enumerate(c['items'], 1):
            rows.append(f"    ({a(ir['r'])}, {a(ir['line'])}, " + ", ".join(n(x) for x in ir['t']) + f", {n(ir['strength'])}, {i})")
        L.append(f"""MERGE fin.ScorecardItemRule AS d
USING (SELECT sc.ScorecardId, m.CreditMetricId, v.LineCode, v.T1, v.T2, v.T3, v.T4, v.ReportStrength, v.SortOrder
       FROM (VALUES
{vals(rows)}
            ) AS v (MetricCode, LineCode, T1, T2, T3, T4, ReportStrength, SortOrder)
       JOIN fin.Scorecard AS sc ON sc.Code = {code} AND sc.VersionNo = {ver} AND sc.Status = 'DRAFT'
       JOIN fin.CreditMetric AS m ON m.Code = v.MetricCode) AS s
   ON d.ScorecardId = s.ScorecardId AND d.MetricId = s.CreditMetricId
WHEN NOT MATCHED THEN
    INSERT (ScorecardId, MetricId, LineCode, T1, T2, T3, T4, ReportStrength, SortOrder)
    VALUES (s.ScorecardId, s.CreditMetricId, s.LineCode, s.T1, s.T2, s.T3, s.T4, s.ReportStrength, s.SortOrder);""")
        rows = []
        for ad in M['adjustments'] + c['extra_adjustments']:
            rows.append(f"    ({a(ad['r'])}, {a(ad['stage'])}, {ad['n']}, {a(ad['cap'])}, {n(ad['p'])}, {a(ad['show'])}, {q(ad['ar'])},\n"
                        f"     {q(ad['t'][0])},\n     {q(ad['t'][1])})")
        L.append(f"""MERGE fin.ScorecardAdjustment AS d
USING (SELECT sc.ScorecardId, v.RuleCode, v.Stage, v.Notches, g.RatingGradeId AS CapGradeId, v.ParamValue, v.ShowWhen, v.NameAr, v.TextAr, v.TextEn
       FROM (VALUES
{vals(rows)}
            ) AS v (RuleCode, Stage, Notches, CapGrade, ParamValue, ShowWhen, NameAr, TextAr, TextEn)
       JOIN fin.Scorecard AS sc ON sc.Code = {code} AND sc.VersionNo = {ver} AND sc.Status = 'DRAFT'
       LEFT JOIN fin.RatingGrade AS g ON g.Code = v.CapGrade) AS s
   ON d.ScorecardId = s.ScorecardId AND d.RuleCode = s.RuleCode
WHEN NOT MATCHED THEN
    INSERT (ScorecardId, RuleCode, Stage, Notches, CapGradeId, ParamValue, ShowWhen, IsActive, NameAr, TextAr, TextEn)
    VALUES (s.ScorecardId, s.RuleCode, s.Stage, s.Notches, s.CapGradeId, s.ParamValue, s.ShowWhen, 1, s.NameAr, s.TextAr, s.TextEn);
UPDATE fin.Scorecard SET Status = 'APPROVED', EffectiveFrom = '{EFFECTIVE}'
WHERE Code = {code} AND VersionNo = {ver} AND Status = 'DRAFT';
GO""")
    return "\n".join(L) + "\n"


def fmt(x):
    if x is None:
        return '—'
    s = f'{x:,.6f}'.rstrip('0').rstrip('.')
    return s


def doc_tables():
    T = {}
    unit_ar = {'RATIO': 'مرة', 'PERCENT': '%', 'DAYS': 'يوم', 'AMOUNT': 'مليون', 'GRADE': 'درجة'}
    dir_ar = {'HIGHER_BETTER': 'الأعلى أفضل', 'LOWER_BETTER': 'الأدنى أفضل', 'NONE': '—'}
    band_ar = {k: v[0] for k, v in M['band_text'].items()}
    r = ['| الدرجة | الرتبة | الفئة | المجال على الخط | المخاطر | درجة استثمار | المعنى |', '|---|---|---|---|---|---|---|']
    for g in M['grades']:
        rng = '—' if g['from'] is None else f"{fmt(g['from'])} ≤ x < {fmt(g['to'])}" if g['code'] != 'Ca' else f"x ≥ {fmt(g['from'])}"
        if g['code'] == 'Aaa':
            rng = 'x < 1.5'
        r.append(f"| {g['code']} | {g['notch']} | {g['category']} | {rng} | {band_ar[g['band']]} | {'نعم' if g['ig'] else 'لا'} | {M['category_text'][g['category']][0]} |")
    T['grades'] = '\n'.join(r)
    r = ['| الرمز | المقياس | الوحدة | الاتجاه | التعريف |', '|---|---|---|---|---|']
    for m in M['metrics']:
        r.append(f"| `{m['code']}` | {m['ar']} | {unit_ar[m['unit']]} | {dir_ar[m['dir']]} | {m['def']} |")
    T['metrics'] = '\n'.join(r)
    fac = M['factor_names']
    for c in M['scorecards']:
        r = ['| العامل | المقياس | الوزن % | أفضل حد (0.5) | Aaa\\|Aa | Aa\\|A | A\\|Baa | Baa\\|Ba | Ba\\|B | B\\|Caa | Caa\\|Ca | أسوأ حد (20.5) |',
             '|---|---|---|---|---|---|---|---|---|---|---|---|']
        for sm in c['metrics']:
            b = sm.get('b') or [None] * 9
            r.append(f"| {fac[sm['f']][0]} | {METRIC[sm['m']]['ar']} | {fmt(sm['w'])} | " + ' | '.join(fmt(x) for x in b) + ' |')
        T['card_' + c['code']] = '\n'.join(r)
        r = ['| البند | المقياس | منخفضة | معتدلة | مرتفعة نسبيًا | مرتفعة | حرجة | نقطة قوة |', '|---|---|---|---|---|---|---|---|']
        for ir in c['items']:
            md, t = METRIC[ir['r']], ir['t']
            if md['dir'] == 'LOWER_BETTER':
                cells = [f'< {fmt(t[0])}', f'{fmt(t[0])} – < {fmt(t[1])}', f'{fmt(t[1])} – < {fmt(t[2])}', f'{fmt(t[2])} – < {fmt(t[3])}', f'≥ {fmt(t[3])}']
            else:
                cells = [f'> {fmt(t[0])}', f'> {fmt(t[1])} – {fmt(t[0])}', f'> {fmt(t[2])} – {fmt(t[1])}', f'> {fmt(t[3])} – {fmt(t[2])}', f'≤ {fmt(t[3])}']
            r.append(f"| `{ir['line']}` | {md['ar']} ({unit_ar[md['unit']]}) | " + ' | '.join(cells) + f" | {'نعم' if ir['strength'] else '—'} |")
        T['items_' + c['code']] = '\n'.join(r)
    stage_ar = {'NOTCH': '1. تنزيل', 'STANDALONE': '2. سقف منفرد', 'ABSOLUTE': '4. سقف مطلق'}
    r = ['| القاعدة | المرحلة | الأثر | المعامل | البطاقات | النص |', '|---|---|---|---|---|---|']
    extra = [(ad, c['code']) for c in M['scorecards'] for ad in c['extra_adjustments']]
    for ad, cards in [(ad, 'كلها') for ad in M['adjustments']] + extra:
        eff = f"تنزيل {abs(ad['n'])}" if ad['n'] else f"لا تتجاوز {ad['cap']}"
        r.append(f"| `{ad['r']}` {ad['ar']} | {stage_ar[ad['stage']]} | {eff} | {fmt(ad['p'])} | {cards} | {ad['t'][0].replace('{p}', fmt(ad['p']) if ad['p'] is not None else '')} |")
    T['adjustments'] = '\n'.join(r)
    # the stress cases of the independent review and the worked example, computed by credit_reference.py
    import io, contextlib, credit_stress, credit_reference as cr
    buf = io.StringIO()
    argv, sys.argv = sys.argv, ['credit_stress.py', '--markdown']
    with contextlib.redirect_stdout(buf):
        credit_stress.main()
    sys.argv = argv
    T['stress'] = buf.getvalue().rstrip()
    ex = cr.assess('GENERAL_CORPORATE', cr.EXAMPLE_CUR, 'ANNUAL', prior=cr.EXAMPLE_PRIOR, qualitative=cr.EXAMPLE_QUAL, **cr.EXAMPLE_DATES)
    card = cr.CARDS['GENERAL_CORPORATE']
    w = {sm['m']: sm['w'] for sm in card['metrics']}
    r = ['| المقياس | القيمة | الدرجة على الخط | الدرجة | الوزن % | المساهمة |', '|---|---|---|---|---|---|']
    tot = sum(w[c] for c, st, v, sc in ex['factors'] if sc is not None)
    for c, st, v, sc in ex['factors']:
        val = fmt(round(v, 2)) if v is not None else ('تقدير المحلل' if st == 'ANALYST' else '—')
        r.append(f"| {METRIC[c]['ar']} | {val} | {sc:.4f} | {cr.grade_of_score(sc)} | {fmt(w[c])} | {w[c] * sc / tot:.4f} |")
    r.append(f"| **المجموع الموزون** | | **{ex['aggregate']:.4f}** | **{ex['indicated']}** | 100 | |")
    T['example'] = '\n'.join(r)
    lv_ar = {'LOW': 'منخفضة', 'MODERATE': 'معتدلة', 'ELEVATED': 'مرتفعة نسبيًا', 'HIGH': 'مرتفعة', 'CRITICAL': 'حرجة', 'NOT_ASSESSED': 'لم يُقيَّم'}
    r = ['| البند | المقياس | القيمة | المستوى |', '|---|---|---|---|']
    for ir in card['items']:
        lvl, v = ex['items'][ir['r']]
        r.append(f"| `{ir['line']}` | {METRIC[ir['r']]['ar']} | {'—' if v is None else fmt(round(v, 2))} | {lv_ar[lvl]} |")
    T['example_items'] = '\n'.join(r)
    T['example_result'] = (f"المجموع المالي (المقاييس الكمية وحدها) {ex['financial']:.4f} أي {ex['financial_grade']}؛ والمجموع الموزون مع العاملين النوعيين "
                           f"{ex['aggregate']:.4f} أي **{ex['indicated']}**؛ ولا تنزيل ولا سقف يغيّرها، فالدرجة المنفردة {ex['standalone']} والنهائية **{ex['final']}**.")
    return T


def render_doc(s):
    for name, body in doc_tables().items():
        pat = re.compile(r'(<!-- gen:%s -->\n).*?(<!-- /gen:%s -->)' % (re.escape(name), re.escape(name)), re.S)
        if not pat.search(s):
            raise SystemExit(f'docs/35 has no markers for {name}')
        s = pat.sub(lambda m: m.group(1) + body + '\n' + m.group(2), s)
    return s


if __name__ == '__main__':
    check()
    open(OUT, 'w', encoding='utf-8').write(seed())
    print(f"wrote {OUT}: {len(M['grades'])} grades, {len(M['metrics'])} metrics, {len(M['scorecards'])} scorecards")
    current = open(DOC, encoding='utf-8').read()
    if '--doc' in sys.argv:
        open(DOC, 'w', encoding='utf-8').write(render_doc(current))
        print(f'updated the generated tables of {DOC}')
    if '--doc-check' in sys.argv and render_doc(current) != current:
        print('docs/35 is stale: run tools/dbgen/gen_credit_seed.py --doc and commit the result')
        sys.exit(1)
