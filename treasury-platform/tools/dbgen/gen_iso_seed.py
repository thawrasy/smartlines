#!/usr/bin/env python3
"""gen_iso_seed.py — writes db/seed/101_iso_reference.sql: the ISO 3166-1 countries and ISO 4217 currencies
(DQ-B05-5, owner decision 2026-10-12: complete lists with IsActive, and the ISO data version recorded).

Usage: PYTHONPATH=<babel> python3 tools/dbgen/gen_iso_seed.py [iso-codes json dir] [out.sql]
Sources:
  - codes and English names: the Debian iso-codes JSON files (default /usr/share/iso-codes/json); the version is
    read from dpkg and written into the SQL header;
  - Arabic names: CLDR through Babel (Locale('ar').territories and .currencies);
  - decimals: the minor units of ISO 4217 itself (CLDR's own digits differ, e.g. IQD), in MINOR_UNITS below;
  - ISO 4217 changes after the iso-codes version, in AMENDMENTS below.
The generated file is committed; CI does not need Babel. Run again only to take a new ISO version.
"""
import json, os, subprocess, sys

from babel import Locale
import babel

SRC = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/iso-codes/json'
OUT = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(__file__), '..', '..', 'db', 'seed', '101_iso_reference.sql')

# ISO 4217 minor units that are not 2. Codes with no minor unit (metals, SDR, test and unit codes) are not seeded.
MINOR_UNITS = {
    **{c: 0 for c in 'BIF CLP DJF GNF ISK JPY KMF KRW PYG RWF UGX VND VUV XAF XOF XPF'.split()},
    **{c: 3 for c in 'BHD IQD JOD KWD LYD OMR TND'.split()},
}
# Not currencies a treasury pays in: precious metals, units of account, funds codes and test codes. CLF and UYW have
# four decimals, which ref.Currency does not allow (CHECK Decimals BETWEEN 0 AND 3).
NOT_SEEDED = set('XAG XAU XPD XPT XBA XBB XBC XBD XDR XSU XUA XTS XXX BOV CHE CHW COU MXV USN UYI CLF UYW'.split())
# ISO 4217 changes after the iso-codes version used: new codes (numeric, English, Arabic) and withdrawn ones.
AMENDMENTS_NEW = {
    'ZWG': ('924', 'Zimbabwe Gold', 'ذهب زيمبابوي'),          # replaces ZWL (2024)
    'XCG': ('532', 'Caribbean Guilder', 'غيلدر كاريبي'),        # replaces ANG (2025)
}
# Withdrawn codes are not seeded: a new platform holds no history in them, and ISO reuses some numeric codes (XCG
# took 532 from ANG), which ref.Currency keeps unique. A currency withdrawn later is set inactive, not deleted.
WITHDRAWN = {'HRK': 'euro in Croatia from 2023', 'SLL': 'replaced by SLE', 'ZWL': 'replaced by ZWG', 'ANG': 'replaced by XCG'}
# Arabic names CLDR does not have yet
AR_EXTRA = {'VED': 'بوليفار سيادي فنزويلي'}
# The six GCC states (BR-CAT-018, 11-m2-m4 section 6.4): weekend and dial code; the weekends are proposals to verify.
GCC = {'SA': ('FRI,SAT', '+966'), 'AE': ('SAT,SUN', '+971'), 'KW': ('FRI,SAT', '+965'),
       'QA': ('FRI,SAT', '+974'), 'BH': ('FRI,SAT', '+973'), 'OM': ('FRI,SAT', '+968')}


def q(s):
    return "N'" + s.replace("'", "''") + "'"


def main():
    try:
        version = subprocess.run(['dpkg-query', '-W', '-f=${Version}', 'iso-codes'], capture_output=True, text=True).stdout.strip()
    except OSError:
        version = 'unknown'
    ar = Locale('ar')
    countries = json.load(open(os.path.join(SRC, 'iso_3166-1.json'), encoding='utf-8'))['3166-1']
    currencies = json.load(open(os.path.join(SRC, 'iso_4217.json'), encoding='utf-8'))['4217']

    crow = []
    for c in sorted(countries, key=lambda x: x['alpha_2']):
        en = c.get('common_name', c['name'])
        name_ar = ar.territories[c['alpha_2']]
        wk, dial = GCC.get(c['alpha_2'], (None, None))
        crow.append(f"    ('{c['alpha_2']}', '{c['alpha_3']}', {q(name_ar)}, {q(en)}, {1 if c['alpha_2'] in GCC else 0}, "
                    f"{('%r' % wk) if wk else 'NULL'}, {('%r' % dial) if dial else 'NULL'})")
    rows = []
    for c in currencies:
        code = c['alpha_3']
        if code in NOT_SEEDED or code in WITHDRAWN:
            continue
        name_ar = AR_EXTRA.get(code) or ar.currencies.get(code)
        if not name_ar:
            raise SystemExit(f'no Arabic name for {code}')
        rows.append((code, c['numeric'], c['name'], name_ar))
    for code, (num, en, name_ar) in AMENDMENTS_NEW.items():
        if code not in {r[0] for r in rows}:
            rows.append((code, num, en, name_ar))
    rows.sort()
    yrow = [f"    ('{code}', '{num}', {q(name_ar)}, {q(en)}, {MINOR_UNITS.get(code, 2)}, 1)"
            for code, num, en, name_ar in rows]

    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(f"""/* ============================================================================
   BankFas - 101: ISO countries and currencies (DQ-B05-5, owner decision 2026-10-12; DOC-B05 section 4.1)
   GENERATED by tools/dbgen/gen_iso_seed.py — do not edit by hand.

   Data version: Debian iso-codes {version} (ISO 3166-1 and ISO 4217 codes and English names), Arabic names from
   CLDR through Babel {babel.__version__}, decimals from the ISO 4217 minor units. ISO 4217 changes after that iso-codes
   version are applied: new {', '.join(sorted(AMENDMENTS_NEW))}; withdrawn {', '.join(sorted(WITHDRAWN))}.
   Not seeded: withdrawn codes (ISO reuses numeric codes, which stay unique here), metals, units of account, funds and
   test codes, and the four-decimal CLF and UYW (ref.Currency allows 0 to 3 decimals). A currency withdrawn later is
   set inactive.
   Countries: all {len(crow)} of ISO 3166-1, English short names in their common form where iso-codes gives one.
   IsGcc, WeekendDays and DialCode are set for the six GCC states only (BR-CAT-018); their weekends are proposals to
   verify before production (Q-CAT-12). The other dial codes need an ITU source (open in O-25).
   Insert only: a row that exists is never changed, so an operator's later correction stays (FR-CAT-026).
   ============================================================================ */
SET NOCOUNT ON;
SET ANSI_NULLS ON; SET QUOTED_IDENTIFIER ON; SET ANSI_PADDING ON; SET ANSI_WARNINGS ON; SET ARITHABORT ON; SET CONCAT_NULL_YIELDS_NULL ON; SET NUMERIC_ROUNDABORT OFF;
GO
MERGE ref.Country AS d
USING (VALUES
{",\n".join(crow)}
) AS s (Iso2, Iso3, NameAr, NameEn, IsGcc, WeekendDays, DialCode)
   ON d.Iso2 = s.Iso2
WHEN NOT MATCHED THEN
    INSERT (Iso2, Iso3, NameAr, NameEn, IsGcc, WeekendDays, DialCode, IsActive)
    VALUES (s.Iso2, s.Iso3, s.NameAr, s.NameEn, s.IsGcc, s.WeekendDays, s.DialCode, 1);
GO
MERGE ref.Currency AS d
USING (VALUES
{",\n".join(yrow)}
) AS s (Code, NumericCode, NameAr, NameEn, Decimals, IsActive)
   ON d.Code = s.Code
WHEN NOT MATCHED THEN
    INSERT (Code, NumericCode, NameAr, NameEn, Decimals, IsActive)
    VALUES (s.Code, s.NumericCode, s.NameAr, s.NameEn, s.Decimals, s.IsActive);
GO
""")
    print(f'wrote {OUT}: {len(crow)} countries, {len(yrow)} currencies')


if __name__ == '__main__':
    main()
