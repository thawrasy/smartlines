#!/usr/bin/env python3
"""fin_lines_pack.py — writes the tenant pack FIN.LINES v1 (db/seed/packs/FIN.LINES/v1/) from the global standard lines
of db/seed/104_credit_methodology.sql (fin.StandardLine), so the tenant catalogue and the credit engine's join by Code
(db/static/047) can never drift apart (S2-b brief S2B-GAP-3, owner default OQ-1: all 157 lines are installed).

  python3 tools/dbgen/fin_lines_pack.py           write the pack
  python3 tools/dbgen/fin_lines_pack.py --check   exit 1 when the pack on disk differs from what would be written

Every line is a system line (IsSystem = 1) with the SeedKey FIN.LINES.<Code>. A line is locked (it cannot be deactivated,
FR-FIN-001) when it is a total, a component of a total, or read by a formula template of FIN.FORMULAS. The entry grid
shows the 51 lines of spec 12 section 6.6 by default (BankFas.Core Finance.LineCatalog.SpecLines); the others are
details of their section.
"""
import csv, glob, io, json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
SEED = glob.glob(os.path.join(ROOT, 'db', 'seed', '104_*.sql'))[0]
FORMULAS = os.path.join(ROOT, 'db', 'seed', 'packs', 'FIN.FORMULAS')
OUT = os.path.join(ROOT, 'db', 'seed', 'packs', 'FIN.LINES', 'v1')

ROW = re.compile(r"\('([A-Z0-9_]+)', '(\w+)', '(\w+)', (NULL|'[A-Z0-9_]+'), N'((?:[^']|'')*)', N'((?:[^']|'')*)', ([01]), "
                 r"(NULL|N?'(?:[^']|'')*'), (\d+)\)")
CODE = re.compile(r'\b[A-Z][A-Z0-9_]*\b')


def standard_lines():
    text = open(SEED, encoding='utf-8').read()
    block = text[text.index('MERGE fin.StandardLine AS d'):text.index(') AS s (Code, Section, LineKind')]
    rows = []
    for code, section, kind, parent, ar, en, req, formula, order in ROW.findall(block):
        f = None if formula == 'NULL' else re.sub(r"^N?'|'$", '', formula).replace("''", "'")
        rows.append(dict(Code=code, Section=section, LineKind=kind, Parent=None if parent == 'NULL' else parent.strip("'"),
                         NameAr=ar.replace("''", "'"), NameEn=en.replace("''", "'"), IsRequired=req, TotalFormula=f, SortOrder=int(order)))
    return rows


def formula_codes():
    used = set()
    for path in glob.glob(os.path.join(FORMULAS, 'v*', 'fin.MeasureFormula.csv')):
        for r in csv.DictReader(open(path, encoding='utf-8')):
            used |= set(CODE.findall(r['Expression']))
    return used


def render():
    lines = standard_lines()
    codes = {l['Code'] for l in lines}
    used = formula_codes() & codes
    for l in lines:
        if l['TotalFormula']:
            used |= set(CODE.findall(l['TotalFormula'])) & codes
    out = io.StringIO()
    w = csv.writer(out, lineterminator='\n')
    w.writerow(['Code', 'NameAr', 'NameEn', 'Description', 'IsActive', 'IsSystem', 'IsLocked', 'SortOrder', 'SeedKey', 'Section', 'IsTotal',
                'TotalFormula', 'IsRequired'])
    for l in sorted(lines, key=lambda l: (l['SortOrder'], l['Code'])):
        total = l['LineKind'] == 'TOTAL'
        locked = total or l['Code'] in used
        desc = {'OF_WHICH': 'Of which, part of %s', 'DETAIL': 'Detail of %s'}.get(l['LineKind'])
        w.writerow([l['Code'], l['NameAr'], l['NameEn'], desc % l['Parent'] if desc else ('Memorandum item' if l['LineKind'] == 'MEMO' else ''),
                    1, 1, 1 if locked else 0, l['SortOrder'], 'FIN.LINES.' + l['Code'], l['Section'], 1 if total else 0,
                    l['TotalFormula'] or '', l['IsRequired']])
    manifest = {
        "PackKey": "FIN.LINES",
        "SeedVersion": 1,
        "Slice": "S2-b",
        "Status": "Generated by tools/dbgen/fin_lines_pack.py from the global standard lines of db/seed/104 (fin.StandardLine), "
                  "themselves a proposed default written by an AI agent (🟡 to be reviewed by the treasury manager). All %d lines are "
                  "installed (owner default OQ-1 of S2-b, 2026-10-23); the entry grid shows the 51 of spec 12 section 6.6 first." % len(lines),
        "Tables": ["fin.LineCatalogItem.csv"],
        "DependsOn": [],
        "References": {},
        "Sources": [
            "db/seed/104_credit_methodology.sql (fin.StandardLine, fin.StandardLineTotal)",
            "docs/10-detailed-analysis/12-m5-facilities-pricing-collateral-obligations.md FR-FIN-001 and section 6.6 (LineCatalogItem)",
            "db/model/14-collateral-obligations-financials.model (fin.LineCatalogItem)",
        ],
        "Notes": {
            "IsLocked": "Totals, the components of a total and the lines a formula template reads: they cannot be deactivated (FR-FIN-001).",
            "Description": "The kind of a standard line that is not a line or a total (of which, detail, memorandum); the kind itself stays in fin.StandardLine.",
        },
    }
    return out.getvalue(), json.dumps(manifest, ensure_ascii=False, indent=2) + '\n'


def main():
    csv_text, man = render()
    files = {os.path.join(OUT, 'fin.LineCatalogItem.csv'): csv_text, os.path.join(OUT, 'manifest.json'): man}
    if '--check' in sys.argv:
        stale = [p for p, t in files.items() if not os.path.exists(p) or open(p, encoding='utf-8').read() != t]
        for p in stale:
            print('stale: %s (run tools/dbgen/fin_lines_pack.py)' % os.path.relpath(p, ROOT))
        sys.exit(1 if stale else 0)
    os.makedirs(OUT, exist_ok=True)
    for p, t in files.items():
        open(p, 'w', encoding='utf-8', newline='').write(t)
    print('FIN.LINES v1: %d lines' % (csv_text.count('\n') - 1))


if __name__ == '__main__':
    main()
