#!/usr/bin/env python3
"""ntf_pack.py — checks the tenant packs NTF.BASE and FIN.PROVISION (db/seed/packs/NTF.BASE/v<N>/, DOC-B05 section 6) and writes its
test fixture (ADR 0028).

  python3 tools/dbgen/ntf_pack.py                 check the pack; exit 1 on a finding
  python3 tools/dbgen/ntf_pack.py --write-test    also rewrite the fixture #CNtfPack in db/tests/credit_assessment_tests.sql
                                                  between its markers, from the pack's files

The checks (BR-NTF-008, FR-NTF-012, FR-NTF-021, DOC-F17 6.4):
  - every CSV column is a column of its table in db/model/15-workflow-notifications.model, and every required column
    without a default is there;
  - every placeholder of a template is in the AllowedPlaceholdersJson of its event, and the pack's placeholder map
    covers every allowed placeholder with columns of fin.v_EarlyWarningMessageValues (db/static/051);
  - every event has the four templates (IN_APP and EMAIL, ar and en), and the subject template fits 300 characters;
  - a mandatory or HIGH event is never coalesced (the check of ntf.NotificationEventType);
  - every rule names an event of the pack and a role of CORE.ROLES (TA, TM, FO, TE, FA, RQ, AU, RK) or a permission of
    the catalogue (db/seed/102_permissions.sql);
  - the pack FIN.PROVISION (ADR 0030): its columns against the model, one rate per ageing bucket between 0 and 100.
"""
import csv, json, os, re, sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), '..', '..'))
PACK = os.path.join(ROOT, 'db', 'seed', 'packs', 'NTF.BASE', 'v1')
MODEL = os.path.join(ROOT, 'db', 'model', '15-workflow-notifications.model')
VIEW = os.path.join(ROOT, 'db', 'static', '051_early_warning_job.sql')
TEST = os.path.join(ROOT, 'db', 'tests', 'credit_assessment_tests.sql')
ROLES = {'TA', 'TM', 'FO', 'TE', 'FA', 'RQ', 'AU', 'RK'}   # RK: the risk officer (owner decision 35)
PERMS = os.path.join(ROOT, 'db', 'seed', '102_permissions.sql')
PROVISION = os.path.join(ROOT, 'db', 'seed', 'packs', 'FIN.PROVISION', 'v1')
PMODEL = os.path.join(ROOT, 'db', 'model', '14-collateral-obligations-financials.model')
BEGIN = '-- BEGIN #CNtfPack (generated by tools/dbgen/ntf_pack.py --write-test from db/seed/packs/NTF.BASE/v1; do not edit)'
END = '-- END #CNtfPack'


def model_columns(table, model=MODEL):
    """Columns of a model table: name -> (required, has default)."""
    text = open(model, encoding='utf-8').read()
    m = re.search(r'^table %s\b.*?$(.*?)(?=^table |\Z)' % re.escape(table), text, re.M | re.S)
    cols = {}
    for line in m.group(1).splitlines():
        line = line.split('#')[0].rstrip()
        p = line.split()
        if len(p) < 2 or p[0] in ('unique', 'index', 'check', 'calc'):
            continue
        cols[p[0]] = (' req' in ' ' + ' '.join(p[2:]) + ' ', any(x.startswith('=') for x in p[2:]))
    return cols


def read(name):
    with open(os.path.join(PACK, name), encoding='utf-8', newline='') as f:
        return list(csv.DictReader(f))


def check():
    errs = []
    man = json.load(open(os.path.join(PACK, 'manifest.json'), encoding='utf-8'))
    tables = {'ntf.NotificationEventType': read('ntf.NotificationEventType.csv'),
              'ntf.NotificationRule': read('ntf.NotificationRule.csv'),
              'ntf.NotificationTemplate': read('ntf.NotificationTemplate.csv')}
    refs = {'EventTypeCode', 'RoleSeedKey', 'PermissionCode'}
    for t, rows in tables.items():
        cols = model_columns(t)
        head = set(rows[0].keys())
        for c in head - refs - set(cols):
            errs.append('%s: column %s is not in the model' % (t, c))
        for c, (req, dflt) in cols.items():
            if req and not dflt and c not in head and not (c.endswith('Id') and c[:-2] in ('EventType', 'Role', 'Permission')):
                errs.append('%s: required column %s is missing' % (t, c))
    ev = {e['Code']: e for e in tables['ntf.NotificationEventType']}
    view = open(VIEW, encoding='utf-8').read()
    vcols = set(re.findall(r'\bAS (\w+)', view.split('CREATE OR ALTER VIEW fin.v_EarlyWarningMessageValues')[1].split('\nFROM ')[0]))
    pmap = man['Placeholders']['map']
    for code, e in ev.items():
        allowed = json.loads(e['AllowedPlaceholdersJson'])
        for p in allowed:
            base = pmap.get(p)
            if base is None:
                errs.append('%s: placeholder {%s} has no column in the manifest map' % (code, p))
            elif not ({base, base + 'Ar'} & vcols and ({base} & vcols or base + 'En' in vcols)):
                errs.append('%s: placeholder {%s} maps to %s, not a column of fin.v_EarlyWarningMessageValues' % (code, p, base))
        if (e['IsMandatory'] == '1' or e['DefaultSeverity'] == 'HIGH') and e['CoalesceWindowMinutes'] not in ('', '0'):
            errs.append('%s: a mandatory or HIGH event is never coalesced' % code)
        have = {(t['Channel'], t['Lang']) for t in tables['ntf.NotificationTemplate'] if t['EventTypeCode'] == code}
        for need in [(c, l) for c in ('IN_APP', 'EMAIL') for l in ('ar', 'en')]:
            if need not in have:
                errs.append('%s: no %s template in %s' % (code, need[0], need[1]))
    for t in tables['ntf.NotificationTemplate']:
        e = ev.get(t['EventTypeCode'])
        if e is None:
            errs.append('template of an unknown event %s' % t['EventTypeCode'])
            continue
        allowed = set(json.loads(e['AllowedPlaceholdersJson']))
        for p in re.findall(r'\{(\w+)\}', t['SubjectTemplate'] + t['BodyTemplate']):
            if p not in allowed:
                errs.append('%s %s %s: placeholder {%s} is not allowed' % (t['EventTypeCode'], t['Channel'], t['Lang'], p))
        if len(t['SubjectTemplate']) > 300:
            errs.append('%s %s %s: subject over 300 characters' % (t['EventTypeCode'], t['Channel'], t['Lang']))
    for r in tables['ntf.NotificationRule']:
        if r['EventTypeCode'] not in ev:
            errs.append('rule %s: unknown event' % r['SeedKey'])
        if r['RecipientKind'] == 'ROLE' and r['RoleSeedKey'].replace('ROLE.', '') not in ROLES:
            errs.append('rule %s: role %s is not of CORE.ROLES' % (r['SeedKey'], r['RoleSeedKey']))
        if r['RecipientKind'] == 'PERMISSION' and ("('%s'," % r['PermissionCode']) not in open(PERMS, encoding='utf-8').read():
            errs.append('rule %s: permission %s is not in the catalogue' % (r['SeedKey'], r['PermissionCode']))
        if (r['RecipientKind'] == 'ROLE') != bool(r['RoleSeedKey']) or (r['RecipientKind'] == 'PERMISSION') != bool(r['PermissionCode']):
            errs.append('rule %s: a ROLE rule names a role and a PERMISSION rule a permission' % r['SeedKey'])
    with open(os.path.join(PROVISION, 'fin.ReceivableLossRate.csv'), encoding='utf-8', newline='') as f:
        rates = list(csv.DictReader(f))
    cols = model_columns('fin.ReceivableLossRate', PMODEL)
    for c in set(rates[0].keys()) - set(cols):
        errs.append('fin.ReceivableLossRate: column %s is not in the model' % c)
    buckets = ['AR_AGE_0_90', 'AR_AGE_91_180', 'AR_AGE_181_365', 'AR_AGE_OVER_365', 'AR_AGE_OVER_365_GOV']
    if sorted(r['BucketCode'] for r in rates) != sorted(buckets):
        errs.append('FIN.PROVISION: one rate per ageing bucket %s' % buckets)
    for r in rates:
        if not 0 <= float(r['LossRatePct']) <= 100:
            errs.append('FIN.PROVISION: rate of %s out of 0..100' % r['BucketCode'])
    tables['fin.ReceivableLossRate'] = rates
    return errs, tables


def q(v):
    return "NULL" if v == '' else "N'" + v.replace("'", "''").replace('\n', "' + NCHAR(10) + N'") + "'"


def fixture(tables):
    """A procedure that seeds the packs NTF.BASE and FIN.PROVISION into the test tenant ('t' in #C) as ITenantSeeder would, roles included."""
    out = [BEGIN, 'CREATE PROCEDURE #CNtfPack', 'AS', 'BEGIN', '    SET NOCOUNT ON;',
           "    DECLARE @t INT = (SELECT v FROM #C WHERE k = 't');"]
    roles = sorted({r['RoleSeedKey'] for r in tables['ntf.NotificationRule'] if r['RoleSeedKey']})
    out.append('    INSERT sec.Role (TenantId, Code, NameAr, NameEn, IsSystem, SeedKey)')
    out.append('    SELECT @t, v.Code, v.Code, v.Code, 1, v.SeedKey FROM (VALUES %s) AS v (Code, SeedKey)'
               % ', '.join("('%s', '%s')" % (k.replace('ROLE.', ''), k) for k in roles))
    out.append('    WHERE NOT EXISTS (SELECT 1 FROM sec.Role AS r WHERE r.TenantId = @t AND r.SeedKey = v.SeedKey);')
    for e in tables['ntf.NotificationEventType']:
        out.append('    INSERT ntf.NotificationEventType (TenantId, %s) VALUES (@t, %s);'
                   % (', '.join(e.keys()), ', '.join(q(v) if k not in ('IsMandatory', 'IsActionRequired', 'DedupWindowMinutes', 'CoalesceWindowMinutes')
                                                     else (v or 'NULL') for k, v in e.items())))
    for r in tables['ntf.NotificationRule']:
        if r['RecipientKind'] == 'PERMISSION':
            out.append("    INSERT ntf.NotificationRule (TenantId, EventTypeId, RecipientKind, PermissionId, RequireCompanyScope, IsMandatory, IsActive, SeedKey)")
            out.append("    SELECT @t, e.NotificationEventTypeId, %s, p.PermissionId, %s, %s, %s, %s FROM ntf.NotificationEventType AS e CROSS JOIN sec.Permission AS p WHERE e.TenantId = @t AND e.Code = %s AND p.Code = %s;"
                       % (q(r['RecipientKind']), r['RequireCompanyScope'], r['IsMandatory'], r['IsActive'], q(r['SeedKey']), q(r['EventTypeCode']), q(r['PermissionCode'])))
            continue
        out.append("    INSERT ntf.NotificationRule (TenantId, EventTypeId, RecipientKind, RoleId, RequireCompanyScope, IsMandatory, IsActive, SeedKey)")
        out.append("    SELECT @t, e.NotificationEventTypeId, %s, r.RoleId, %s, %s, %s, %s FROM ntf.NotificationEventType AS e JOIN sec.Role AS r ON r.TenantId = e.TenantId AND r.SeedKey = %s WHERE e.TenantId = @t AND e.Code = %s;"
                   % (q(r['RecipientKind']), r['RequireCompanyScope'], r['IsMandatory'], r['IsActive'], q(r['SeedKey']), q(r['RoleSeedKey']), q(r['EventTypeCode'])))
    for r in tables['fin.ReceivableLossRate']:
        out.append("    INSERT fin.ReceivableLossRate (TenantId, BucketCode, LossRatePct, EffectiveFrom, Status, Note, SeedKey) VALUES (@t, %s, %s, %s, %s, %s, %s);"
                   % (q(r['BucketCode']), r['LossRatePct'], q(r['EffectiveFrom']), q(r['Status']), q(r['Note']), q(r['SeedKey'])))
    for t in tables['ntf.NotificationTemplate']:
        out.append("    INSERT ntf.NotificationTemplate (TenantId, EventTypeId, Channel, Lang, SubjectTemplate, BodyTemplate, IsTenantOverride)")
        out.append("    SELECT @t, NotificationEventTypeId, %s, %s, %s, %s, %s FROM ntf.NotificationEventType WHERE TenantId = @t AND Code = %s;"
                   % (q(t['Channel']), q(t['Lang']), q(t['SubjectTemplate']), q(t['BodyTemplate']), t['IsTenantOverride'], q(t['EventTypeCode'])))
    out += ['END;', 'GO', END]
    return '\n'.join(out)


def main():
    errs, tables = check()
    for e in errs:
        print('FAIL', e)
    if errs:
        sys.exit(1)
    n = sum(len(v) for v in tables.values())
    if '--write-test' in sys.argv:
        s = open(TEST, encoding='utf-8').read()
        i, j = s.index(BEGIN), s.index(END) + len(END)
        open(TEST, 'w', encoding='utf-8').write(s[:i] + fixture(tables) + s[j:])
        print('wrote #CNtfPack into', os.path.relpath(TEST, ROOT))
    print('NTF.BASE pack: OK (%d events, %d rules, %d templates); FIN.PROVISION pack: OK (%d rates); %d rows' % (
        len(tables['ntf.NotificationEventType']), len(tables['ntf.NotificationRule']), len(tables['ntf.NotificationTemplate']),
        len(tables['fin.ReceivableLossRate']), n))


if __name__ == '__main__':
    main()
