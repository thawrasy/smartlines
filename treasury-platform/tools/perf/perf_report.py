#!/usr/bin/env python3
"""perf_report.py — writes the report of a performance run (tools/perf/run_perf.sh; ADR 0036) from its raw lines.

Usage: python3 tools/perf/perf_report.py <perf-run.txt> <perf-results.md>
Every number in the report comes from the raw lines; nothing is typed by hand. A scenario with a target is PASS when
its p95 is within it. Targets: NFR-PERF-06 for the binding; for what a screen reads, a database budget of 200 ms,
a tenth of the 2 seconds of NFR-PERF-01 (a proposal, DQ-B03-11); the jobs and the deployment window have no target
in DOC-B03 and are reported only.
"""
import sys

SCENARIOS = {   # id: (what is measured, target in ms or None, the requirement)
    'B1': ('Session binding sec.usp_SetSessionContext, a new connection per call', 20, 'NFR-PERF-06'),
    'Q1': ('Audit viewer: latest 50 rows of the tenant', 200, 'NFR-PERF-01 (database share)'),
    'Q2': ('Audit viewer: latest 50 treasury rows', 200, 'NFR-PERF-01 (database share)'),
    'Q3': ('Company list: a page of 50', 200, 'NFR-PERF-01 (database share)'),
    'Q4': ('A company\'s statements with their lines', 200, 'NFR-PERF-01 (database share)'),
    'R1': ('Credit report of an assessment: header and findings', 200, 'NFR-PERF-01 (database share)'),
    'R2': ('Early warnings of the whole tenant (readiness screen)', 2000, 'NFR-PERF-01'),
    'R3': ('Covenant breach report of the tenant', 2000, 'NFR-PERF-01'),
    'W1': ('One audit row with its place in the hash chain', 200, 'NFR-PERF-01 (database share)'),
    'W2': ('Credit computation of one assessment', None, 'no target (user action, runs once)'),
    'W3': ('Evidence pack of an endorsed assessment', None, 'no target (user action, runs once)'),
    'J1': ('Daily early warning job of the tenant', None, 'no target (nightly job)'),
    'J2': ('Full audit chain verification of the tenant (every row)', None, 'no target (weekly job)'),
    'J3': ('Anchors of all chains', None, 'no target (daily job)'),
    'J4': ('Daily chain check from the anchor (a day of 500 rows)', None, 'no target (daily job)'),
    'D1': ('Schema fingerprint', None, 'no target (deployment)'),
    'D2': ('Repeatable scripts on the loaded database (migrate.sh apply --repeatable)', None, 'no target (deployment window)'),
}


def main():
    raw, out = sys.argv[1], sys.argv[2]
    run, gen, res, info, size, top, miss, conc = {}, [], {}, [], [], [], [], None
    for line in open(raw, encoding='utf-8'):
        f = line.rstrip('\n').split('|')
        k = f[0]
        if k == 'RUN':
            run[f[1]] = f[2]
        elif k == 'GEN':
            gen.append(f[1:])
        elif k == 'RESULT' and f[1] == 'C1':
            conc = f[2:]
        elif k == 'RESULT':
            res[f[1]] = f[2:]
        elif k == 'INFO':
            info.append(f[1:])
        elif k == 'SIZE':
            size.append(f[1:])
        elif k == 'TOP':
            top.append(f[1:])
        elif k == 'MISSING':
            miss.append(f[1:])
    w = []
    w.append('# Performance run of the database\n')
    w.append('Generated by `tools/perf/perf_report.py` from `docs/perf/perf-run.txt` (ADR 0036). Do not edit by hand.\n')
    w.append('| Item | Value |\n|---|---|')
    for key in ('started', 'finished', 'commit', 'server', 'host', 'sizes', 'deploy seconds', 'seed seconds'):
        if key in run:
            w.append(f'| {key} | {run[key]} |')
    w.append('\n## Data generation\n')
    w.append('| Step | Value |\n|---|---|')
    for g in gen:
        if g[0] == 'compute':
            w.append(f'| credit computations while generating | {g[1]} runs, mean {g[2]} ms, max {g[3]} ms |')
        else:
            w.append(f'| {g[0]} | {g[1]} s |')
    w.append('\n## Results\n')
    w.append('| Id | What | Samples | p50 ms | p95 ms | max ms | Target ms | Requirement | Status |')
    w.append('|---|---|---|---|---|---|---|---|---|')
    for sid, (what, target, req) in SCENARIOS.items():
        if sid not in res:
            continue
        n, p50, p95, mx = res[sid]
        status = 'reported' if target is None else ('PASS' if float(p95) <= target else 'OVER')
        w.append(f'| {sid} | {what} | {n} | {p50} | {p95} | {mx} | {target if target is not None else "—"} | {req} | {status} |')
    if conc:
        rows, ms, rate = conc
        w.append(f'\nConcurrent audit writers (C1): {rows} rows in {ms} ms, {rate} rows a second, one tenant\'s chain.')
    if info:
        w.append('\n| Note | Value |\n|---|---|')
        for i in info:
            w.append(f'| {i[0]} {i[1]} | {i[2] if len(i) > 2 else ""} |')
    w.append('\n## Sizes\n')
    w.append('| Table | Rows |\n|---|---|')
    for s in size:
        w.append(f'| {s[0]} | {s[1]} |')
    w.append('\n## Costliest statements of the measurement (total CPU)\n')
    w.append('| Object | Runs | CPU ms | Logical reads | Statement |\n|---|---|---|---|---|')
    for t in top:
        text = t[4].replace('|', '/') if len(t) > 4 else ''
        w.append(f'| {t[0]} | {t[1]} | {t[2]} | {t[3]} | `{text.strip()}` |')
    w.append('\n## Indexes the optimiser asked for\n')
    if miss:
        w.append('| Table | Equality | Inequality | Include | Impact % | Uses |\n|---|---|---|---|---|---|')
        for m in miss:
            w.append(f'| {m[0]} | {m[1]} | {m[2]} | {m[3]} | {m[4]} | {m[5]} |')
    else:
        w.append('None.')
    open(out, 'w', encoding='utf-8').write('\n'.join(w) + '\n')
    over = [sid for sid, (_, target, _) in SCENARIOS.items() if sid in res and target is not None and float(res[sid][2]) > target]
    print(f'wrote {out}: {len(res)} scenarios, over target: {", ".join(over) or "none"}')


if __name__ == '__main__':
    main()
