using System.Globalization;
using System.Security.Cryptography;
using System.Text;
using BankFas.Core.Files;
using BankFas.Core.Security;
using BankFas.Data;
using BankFas.Data.Lc;
using Dapper;
using Microsoft.Data.SqlClient;

namespace BankFas.Api.Infrastructure;

/// <summary>
/// What the issue of a proforma takes from the application (S4, FR-LCE-005; BR-LCE-004): the proceeds account's IBAN
/// opened with the tenant's DATA key, printed for the customer on purpose and so audited by the issue itself; and the
/// printed proforma stored like an upload, encrypted with the tenant's FILE key under the tenant's PublicId, as version
/// 1 of a PROFORMA_ISSUED document of the company linked to the request. A generated document is not scanned: the
/// platform wrote it. Registered as ProformaStore.Services when the API starts.
/// </summary>
public sealed class ProformaServices(TenantKeyRing keys, FileStore store) : IProformaServices
{
    private static async Task<int> TenantAsync(SqlConnection c, SqlTransaction tx, CancellationToken ct) =>
        await c.ExecuteScalarAsync<int>(new CommandDefinition("SELECT CAST(SESSION_CONTEXT(N'TenantId') AS INT);", transaction: tx, cancellationToken: ct)).ConfigureAwait(false);

    public async Task<string?> AccountIbanAsync(SqlConnection c, SqlTransaction tx, long bankAccountId, CancellationToken ct)
    {
        var row = await c.QuerySingleAsync<(Guid PublicId, byte[]? IbanEnc, long KeyId)>(new CommandDefinition(
            "SELECT PublicId, IbanEnc, EncKeyId FROM acc.BankAccount WHERE BankAccountId = @a;", new { a = bankAccountId }, tx, cancellationToken: ct)).ConfigureAwait(false);
        if (row.IbanEnc is null) return null;
        var tenant = await TenantAsync(c, tx, ct).ConfigureAwait(false);
        var key = await keys.ByIdAsync(c, tx, tenant, row.KeyId, ct).ConfigureAwait(false);
        return Encoding.UTF8.GetString(Envelope.Open(key, row.IbanEnc, EnvelopeAad.ForColumn(tenant, "acc.BankAccount", "IbanEnc", row.PublicId)));
    }

    public async Task<long> StoreAsync(SqlConnection c, SqlTransaction tx, GeneratedDocument document, CancellationToken ct)
    {
        ArgumentNullException.ThrowIfNull(document);
        var d = document;
        var tenant = await TenantAsync(c, tx, ct).ConfigureAwait(false);
        var tenantRef = await c.ExecuteScalarAsync<Guid>(new CommandDefinition("SELECT PublicId FROM plat.v_CurrentTenant;", transaction: tx, cancellationToken: ct)).ConfigureAwait(false);
        var type = await c.QuerySingleAsync<(int Id, bool Sensitive)>(new CommandDefinition(
            "SELECT DocumentTypeId, IsSensitive FROM cat.DocumentType WHERE Code = @code AND IsActive = 1;", new { code = d.TypeCode }, tx, cancellationToken: ct)).ConfigureAwait(false);
        var doc = await c.QuerySingleAsync<(long Id, Guid PublicId)>(new CommandDefinition(
            """
            DECLARE @o TABLE (Id BIGINT, PublicId UNIQUEIDENTIFIER);
            INSERT doc.Document (TenantId, DocumentTypeId, Title, DocumentNumber, IssueDate, OwnerCompanyId, Sensitivity, CreatedBy)
            OUTPUT inserted.DocumentId, inserted.PublicId INTO @o
            VALUES (CAST(SESSION_CONTEXT(N'TenantId') AS INT), @type, @title, @num, @issue, @company, @sens, CAST(SESSION_CONTEXT(N'UserId') AS BIGINT));
            SELECT Id, PublicId FROM @o;
            """, new { type = type.Id, title = d.Title, num = d.Number, issue = d.IssueDate, company = d.CompanyId, sens = type.Sensitive ? "RESTRICTED" : "CONFIDENTIAL" },
            tx, cancellationToken: ct)).ConfigureAwait(false);
        var (keyId, key) = await keys.ActiveAsync(c, tx, tenant, "FILE", ct).ConfigureAwait(false);
        var storageKey = string.Create(CultureInfo.InvariantCulture,
            $"{tenantRef:N}/{doc.PublicId:N}/v1-{Convert.ToHexString(RandomNumberGenerator.GetBytes(8)).ToLowerInvariant()}");
        await store.WriteAsync(storageKey, FileCrypto.Encrypt(key, d.Content, tenant, storageKey, 1), ct).ConfigureAwait(false);
        try
        {
            await c.ExecuteAsync(new CommandDefinition(
                """
                DECLARE @o TABLE (Id BIGINT);
                INSERT doc.DocumentVersion (TenantId, DocumentId, VersionNo, StorageKey, FileName, ContentType, SizeBytes, Sha256, KeyId, ScanStatus, ScannedAt, ScanDetail, CreatedBy)
                OUTPUT inserted.DocumentVersionId INTO @o
                VALUES (CAST(SESSION_CONTEXT(N'TenantId') AS INT), @d, 1, @key, @name, @ctype, @size, @sha, @keyId, 'CLEAN', SYSUTCDATETIME(), N'generated by the platform',
                        CAST(SESSION_CONTEXT(N'UserId') AS BIGINT));
                UPDATE doc.Document SET CurrentVersionId = (SELECT Id FROM @o) WHERE DocumentId = @d;
                INSERT doc.DocumentLink (TenantId, DocumentId, EntityType, EntityId, LinkRole, CreatedBy)
                VALUES (CAST(SESSION_CONTEXT(N'TenantId') AS INT), @d, @et, @eid, 'ATTACHMENT', CAST(SESSION_CONTEXT(N'UserId') AS BIGINT));
                """,
                new
                {
                    d = doc.Id, key = storageKey, name = d.FileName, ctype = d.ContentType, size = (long)d.Content.Length, sha = SHA256.HashData(d.Content), keyId,
                    et = d.LinkEntityType, eid = d.LinkEntityId,
                }, tx, cancellationToken: ct)).ConfigureAwait(false);
            await Outbox.EmitAsync(c, tx, "document.generated", "doc.Document", doc.Id, new { document = doc.PublicId, type = d.TypeCode }, ct).ConfigureAwait(false);
        }
        catch
        {
            store.DeleteUncommitted(storageKey);
            throw;
        }
        return doc.Id;
    }
}
